export function filterGoods({ query = "", category = "all", type = "" } = {}) {
  const keyword = query.trim().toLowerCase();
  return goods.filter(
    (item) =>
      (category === "all" ||
        (category === "personal" && item.personal) ||
        item.category === category) &&
      (!type || item.kind === type) &&
      (!keyword ||
        `${item.title} ${item.seller} ${item.location}`
          .toLowerCase()
          .includes(keyword)),
  );
}
